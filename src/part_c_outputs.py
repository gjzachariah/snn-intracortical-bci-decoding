"""
part_c_outputs.py
=================
Everything needed for CSIT 750 assignment, part (c):

  * builds the small synthetic dataset (96 channels, 8 directions, 800 trials)
  * exports it as readable CSV files (so it can be opened on GitHub)
  * draws the three figures
  * writes the key numbers used in the written explanation

Run from the repository root:
    python src/part_c_outputs.py

It re-uses generate_data.py, so the figures always come from exactly the
synthetic data that script produces (seed 0).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib
import matplotlib.pyplot as plt
from matplotlib.patches import Patch
from matplotlib.lines import Line2D

import generate_data as gd

REPO_ROOT = gd.REPO_ROOT
FIG_DIR = REPO_ROOT / "results" / "figures"
TABLE_DIR = REPO_ROOT / "results" / "tables"
CSV_DIR = REPO_ROOT / "data" / "synthetic" / "assignment_dataset"

# colour-blind-safe colours (Okabe-Ito)
C_PREF, C_OPP, C_NEUTRAL, C_MODEL = "#D55E00", "#0072B2", "#8c8c8c", "#222222"
SPLIT_NAMES = {0: "train", 1: "val", 2: "test"}

plt.rcParams.update({
    "font.size": 10, "axes.titlesize": 11, "axes.labelsize": 10,
    "axes.spines.top": False, "axes.spines.right": False,
    "figure.dpi": 110, "savefig.dpi": 200,
})


# --------------------------------------------------------------------------
# Data helpers
# --------------------------------------------------------------------------
def assignment_config() -> gd.GeneratorConfig:
    """The dataset used in the assignment: 96 channels (one Utah array), 800 trials."""
    return gd.GeneratorConfig(n_channels=96, trials_per_direction=100, seed=0)


def movement_slice(cfg):
    return slice(int(round(cfg.ramp_end_s * 1000 / cfg.bin_ms)), None)


def movement_rates(data) -> np.ndarray:
    """Firing rate (Hz) of every channel in every trial during the movement phase."""
    cfg = gd.GeneratorConfig(**data["config"])
    sl = movement_slice(cfg)
    n_bins = cfg.n_bins - sl.start
    return data["spikes"][:, :, sl].sum(axis=2) / (n_bins * cfg.dt_s)


def active_channels_sorted(data) -> np.ndarray:
    """Indices of non-silent channels, ordered by preferred direction (0 -> 360 deg)."""
    act = np.flatnonzero(~data["is_silent"])
    return act[np.argsort(data["pref_dir_rad"][act])]


# --------------------------------------------------------------------------
# CSV export (small, human-readable dataset)
# --------------------------------------------------------------------------
def export_csv(data, out_dir: Path = CSV_DIR) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    cfg = gd.GeneratorConfig(**data["config"])
    n_trials, n_ch = data["spikes"].shape[:2]

    split = np.empty(n_trials, dtype=object)
    split[data["train_idx"]], split[data["val_idx"]], split[data["test_idx"]] = "train", "val", "test"

    counts = data["spikes"][:, :, movement_slice(cfg)].sum(axis=2)
    df = pd.DataFrame(counts, columns=[f"ch{c:03d}" for c in range(n_ch)])
    df.insert(0, "split", split)
    df.insert(0, "direction", [gd.DIRECTION_NAMES[k] for k in data["labels"]])
    df.insert(0, "direction_index", data["labels"])
    df.insert(0, "trial_id", np.arange(n_trials))
    df.to_csv(out_dir / "spike_counts_movement_window.csv", index=False)

    params = pd.DataFrame({
        "channel": [f"ch{c:03d}" for c in range(n_ch)],
        "is_silent": data["is_silent"],
        "baseline_hz": data["baseline_hz"].round(3),
        "tuning_amplitude_hz": data["amplitude_hz"].round(3),
        "preferred_direction_deg": np.degrees(data["pref_dir_rad"]).round(1),
    })
    params.to_csv(out_dir / "neuron_parameters.csv", index=False)

    (out_dir / "README.md").write_text(
        "# Assignment dataset (CSIT 750, part c)\n\n"
        "Synthetic centre-out reaching data, generated by `src/generate_data.py` "
        "(seed 0, 96 channels, 100 trials per direction = 800 trials). "
        "Re-create it with `python src/part_c_outputs.py`.\n\n"
        "## spike_counts_movement_window.csv\n"
        "One row per trial.\n\n"
        "| column | meaning |\n|---|---|\n"
        "| trial_id | 0-799 |\n"
        "| direction_index / direction | reach direction 0-7 = N, NE, E, SE, S, SW, W, NW |\n"
        "| split | train / val / test (70 / 15 / 15 %, balanced across directions) |\n"
        "| ch000 ... ch095 | number of spikes the channel fired during the 0.5 s movement phase |\n\n"
        "## neuron_parameters.csv\n"
        "The hidden settings of each synthetic neuron: baseline rate, tuning amplitude, "
        "preferred direction, and whether the channel is silent.\n\n"
        "The full trial-by-time spike arrays (800 x 96 x 100) are stored as a compressed "
        "`.npz` file that is not uploaded to GitHub; it is rebuilt from the seed.\n"
    )
    return {"rows": len(df), "columns": df.shape[1]}


# --------------------------------------------------------------------------
# Figure 1 - tuning curves of example neurons
# --------------------------------------------------------------------------
def pick_example_neurons(data, n: int = 6):
    """Strongly tuned neurons whose preferred directions are well spread out.

    Starts with a wide spacing requirement and relaxes it until n neurons are found.
    """
    pref_deg = np.degrees(data["pref_dir_rad"])
    act = np.flatnonzero(~data["is_silent"] & (data["baseline_hz"] >= 2.0))
    order = act[np.argsort(-data["amplitude_hz"][act])][:60]

    def sep(a, b):
        d = abs(a - b) % 360
        return min(d, 360 - d)

    for min_sep in (50.0, 40.0, 30.0, 20.0, 10.0, 0.0):
        chosen = []
        for c in order:
            if all(sep(pref_deg[c], pref_deg[j]) >= min_sep for j in chosen):
                chosen.append(c)
            if len(chosen) == n:
                return sorted(chosen, key=lambda c: pref_deg[c])
    return sorted(chosen, key=lambda c: pref_deg[c])


def figure1_tuning_curves(data):
    labels = data["labels"]
    rates = movement_rates(data)
    picks = pick_example_neurons(data)
    xs = np.linspace(0, 360, 361)
    dirs = np.arange(8) * 45

    fig, axes = plt.subplots(2, 3, figsize=(11, 6.2), sharex=True)
    for ax, c in zip(axes.ravel(), picks):
        means = np.array([rates[labels == k, c].mean() for k in range(8)])
        sems = np.array([rates[labels == k, c].std(ddof=1) / np.sqrt((labels == k).sum()) for k in range(8)])
        pref = data["pref_dir_rad"][c]
        curve = np.clip(data["baseline_hz"][c] + data["amplitude_hz"][c] *
                        np.cos(np.radians(xs) - pref), 0, None)
        ax.plot(xs, curve, color=C_MODEL, lw=1.6, label="Cosine model (intended)")
        ax.errorbar(dirs, means, yerr=sems, fmt="o", color=C_PREF, ms=5, capsize=3,
                    label="Simulated mean ± SEM (100 trials)")
        ax.axvline(np.degrees(pref), color=C_NEUTRAL, ls=":", lw=1)
        ax.set_title(f"Channel {c}  (preferred ≈ {np.degrees(pref):.0f}°)")
        ax.set_xticks(list(dirs) + [360])
        ax.set_xticklabels(gd.DIRECTION_NAMES + ["N"])
        ax.set_ylim(bottom=0)
    for ax in axes[:, 0]:
        ax.set_ylabel("Firing rate (Hz)")
    for ax in axes[1, :]:
        ax.set_xlabel("Reach direction")
    h, l = axes[0, 0].get_legend_handles_labels()
    fig.legend(h, l, loc="lower center", ncol=2, frameon=False, bbox_to_anchor=(0.5, -0.01))
    fig.suptitle("Figure 1. Each synthetic neuron fires most for one preferred reach direction",
                 fontsize=12, y=0.995)
    fig.tight_layout(rect=(0, 0.04, 1, 0.97))

    allc = np.flatnonzero(~data["is_silent"])
    intended = np.stack([gd.expected_rate_hz(data, k)[allc] for k in range(8)])
    measured = np.stack([rates[labels == k][:, allc].mean(axis=0) for k in range(8)])
    stats = {
        "examples": [{"channel": int(c), "preferred_deg": float(np.degrees(data["pref_dir_rad"][c])),
                      "baseline_hz": float(data["baseline_hz"][c]),
                      "amplitude_hz": float(data["amplitude_hz"][c])} for c in picks],
        "corr_intended_vs_measured": float(np.corrcoef(intended.ravel(), measured.ravel())[0, 1]),
    }
    return fig, stats


# --------------------------------------------------------------------------
# Figure 2 - population heatmap
# --------------------------------------------------------------------------
def figure2_population_heatmap(data):
    labels = data["labels"]
    rates = movement_rates(data)
    order = active_channels_sorted(data)
    mean_rate = np.stack([rates[labels == k][:, order].mean(axis=0) for k in range(8)]).T   # (neurons, 8)
    centred = mean_rate - mean_rate.mean(axis=1, keepdims=True)
    vlim = np.percentile(np.abs(centred), 95)

    fig, ax = plt.subplots(figsize=(7.2, 7.6))
    im = ax.imshow(centred, aspect="auto", cmap="RdBu_r", vmin=-vlim, vmax=vlim,
                   origin="lower", interpolation="nearest")
    ax.set_xticks(range(8)); ax.set_xticklabels(gd.DIRECTION_NAMES)
    pref_deg = np.degrees(data["pref_dir_rad"][order])
    ticks = [int(np.searchsorted(pref_deg, a)) for a in (0, 90, 180, 270)]
    ax.set_yticks(ticks); ax.set_yticklabels(["0°", "90°", "180°", "270°"])
    ax.set_xlabel("Reach direction")
    ax.set_ylabel("Neurons, sorted by preferred direction\n(tick = first neuron at that angle)")
    ax.spines[["left", "bottom"]].set_visible(False)
    cb = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.03)
    cb.set_label("Firing rate minus the neuron's own average (Hz)\nred = fires more, blue = fires less")
    ax.set_title("Figure 2. The population's response pattern changes with reach direction",
                 fontsize=11.5, loc="left")
    fig.tight_layout()

    # how well does each neuron's strongest direction agree with its true preferred one?
    best = centred.argmax(axis=1) * 45.0
    diff = np.abs((best - pref_deg + 180) % 360 - 180)
    amp = data["amplitude_hz"][order]
    strong = amp >= np.median(amp)
    stats = {
        "n_neurons_shown": int(len(order)),
        "share_peak_within_45deg_all": float((diff <= 45).mean()),
        "share_peak_within_45deg_strong_half": float((diff[strong] <= 45).mean()),
        "colour_limit_hz": float(vlim),
    }
    return fig, stats


# --------------------------------------------------------------------------
# Figure 3 - raster + time course
# --------------------------------------------------------------------------
def figure3_raster_and_psth(data, direction: int = 2):
    cfg = gd.GeneratorConfig(**data["config"])
    t_ms = np.arange(cfg.n_bins) * cfg.bin_ms
    order = active_channels_sorted(data)
    pref_deg = np.degrees(data["pref_dir_rad"][order])
    dir_deg = direction * 45.0
    delta = np.abs((pref_deg - dir_deg + 180) % 360 - 180)
    is_pref, is_opp = delta <= 45, delta >= 135

    trial_ids = np.flatnonzero(data["labels"] == direction)
    example = trial_ids[0]
    spikes_ex = data["spikes"][example][order]                    # (neurons, T)

    # population time course (mean over trials of this direction)
    mean_rate = data["spikes"][trial_ids][:, order, :].mean(axis=0) / cfg.dt_s   # (neurons, T)
    hold_bins = int(round(cfg.hold_end_s * 1000 / cfg.bin_ms))
    change = mean_rate - mean_rate[:, :hold_bins].mean(axis=1, keepdims=True)
    smooth = lambda a: pd.DataFrame(a.T).rolling(5, center=True, min_periods=1).mean().to_numpy().T
    change = smooth(change)

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8.0), sharex=True,
                                   gridspec_kw={"height_ratios": [2, 1.2], "hspace": 0.28})
    for ax in (ax1, ax2):
        ax.axvspan(0, cfg.hold_end_s * 1000, color="#999999", alpha=0.10, lw=0)
        ax.axvspan(cfg.hold_end_s * 1000, cfg.ramp_end_s * 1000, color="#E69F00", alpha=0.18, lw=0)
        ax.axvspan(cfg.ramp_end_s * 1000, cfg.trial_duration_s * 1000, color="#56B4E9", alpha=0.10, lw=0)

    rows, bins = np.nonzero(spikes_ex)
    colours = np.where(is_pref[rows], C_PREF, np.where(is_opp[rows], C_OPP, C_NEUTRAL))
    ax1.scatter(t_ms[bins], rows, marker="|", s=26, c=colours, linewidths=0.9)
    ax1.set_ylabel("Neurons, sorted by preferred direction")
    fig.suptitle(f"Figure 3. Spiking over time for reaches toward {gd.DIRECTION_NAMES[direction]}",
                 fontsize=11.5, x=0.01, ha="left")
    for x, txt in ((cfg.hold_end_s * 500, "Hold"), ((cfg.hold_end_s + cfg.ramp_end_s) * 500, "Go ramp"),
                   ((cfg.ramp_end_s + cfg.trial_duration_s) * 500, "Movement")):
        ax1.text(x, 1.01, txt, ha="center", va="bottom", fontsize=9, transform=ax1.get_xaxis_transform())
    ax1.set_ylim(-1, len(order) + 1)
    ax1.legend(handles=[
        Line2D([], [], marker="|", ls="", color=C_PREF, label=f"prefers {gd.DIRECTION_NAMES[direction]} (±45°)"),
        Line2D([], [], marker="|", ls="", color=C_OPP, label="prefers the opposite direction"),
        Line2D([], [], marker="|", ls="", color=C_NEUTRAL, label="in between")],
        loc="lower center", fontsize=8, frameon=False, ncol=3, bbox_to_anchor=(0.5, -0.17))

    for mask, col, lab in ((is_pref, C_PREF, f"Neurons preferring {gd.DIRECTION_NAMES[direction]} (n={is_pref.sum()})"),
                           (is_opp, C_OPP, f"Neurons preferring the opposite direction (n={is_opp.sum()})")):
        m = change[mask].mean(axis=0)
        se = change[mask].std(axis=0, ddof=1) / np.sqrt(mask.sum())
        ax2.plot(t_ms, m, color=col, lw=2, label=lab)
        ax2.fill_between(t_ms, m - se, m + se, color=col, alpha=0.2, lw=0)
    ax2.axhline(0, color="k", lw=0.6)
    ax2.set_xlabel("Time in trial (ms)")
    ax2.set_ylabel("Change in rate vs hold (Hz)")
    ax2.legend(loc="center right", fontsize=8, frameon=False)
    ax2.set_xlim(0, cfg.trial_duration_s * 1000 - cfg.bin_ms)
    # tight_layout cannot handle the legend placed outside the axes, so spacing is set by hand
    fig.subplots_adjust(left=0.09, right=0.985, top=0.925, bottom=0.075, hspace=0.38)

    mv = slice(int(round(cfg.ramp_end_s * 1000 / cfg.bin_ms)), None)
    hold = slice(0, hold_bins)
    stats = {
        "example_trial_id": int(example),
        "direction": gd.DIRECTION_NAMES[direction],
        "n_preferring": int(is_pref.sum()), "n_opposite": int(is_opp.sum()),
        "preferring_change_movement_hz": float(change[is_pref][:, mv].mean()),
        "opposite_change_movement_hz": float(change[is_opp][:, mv].mean()),
        "preferring_change_hold_hz": float(change[is_pref][:, hold].mean()),
        "opposite_change_hold_hz": float(change[is_opp][:, hold].mean()),
        "spikes_in_example_trial": int(spikes_ex.sum()),
    }
    return fig, stats


# --------------------------------------------------------------------------
# Dataset summary numbers
# --------------------------------------------------------------------------
def dataset_summary(data) -> dict:
    cfg = gd.GeneratorConfig(**data["config"])
    sp = data["spikes"]
    hold_bins = int(round(cfg.hold_end_s * 1000 / cfg.bin_ms))
    sl = movement_slice(cfg)
    return {
        "trials": int(sp.shape[0]), "channels": int(sp.shape[1]), "time_bins": int(sp.shape[2]),
        "bin_ms": cfg.bin_ms, "trial_duration_s": cfg.trial_duration_s,
        "silent_channels": int(data["is_silent"].sum()),
        "active_channels": int((~data["is_silent"]).sum()),
        "trials_per_direction": cfg.trials_per_direction,
        "train_val_test": [int(len(data["train_idx"])), int(len(data["val_idx"])), int(len(data["test_idx"]))],
        "overall_mean_rate_hz": float(sp.mean() / cfg.dt_s),
        "hold_mean_rate_hz": float(sp[:, :, :hold_bins].mean() / cfg.dt_s),
        "movement_mean_rate_hz": float(sp[:, :, sl].mean() / cfg.dt_s),
        "fraction_of_bins_with_spike": float(sp.mean()),
        "total_spikes": int(sp.sum()),
        "active_baseline_hz_median": float(np.median(data["baseline_hz"][~data["is_silent"]])),
        "active_baseline_hz_max": float(data["baseline_hz"].max()),
        "seed": cfg.seed,
    }


# --------------------------------------------------------------------------
# One call that does everything
# --------------------------------------------------------------------------
def build_everything(save: bool = True):
    cfg = assignment_config()
    data = gd.generate_dataset(cfg)
    stats = {"dataset": dataset_summary(data)}

    f1, s1 = figure1_tuning_curves(data)
    f2, s2 = figure2_population_heatmap(data)
    f3, s3 = figure3_raster_and_psth(data)
    stats.update(fig1=s1, fig2=s2, fig3=s3)

    if save:
        FIG_DIR.mkdir(parents=True, exist_ok=True)
        TABLE_DIR.mkdir(parents=True, exist_ok=True)
        f1.savefig(FIG_DIR / "fig1_tuning_curves_synthetic.png", bbox_inches="tight")
        f2.savefig(FIG_DIR / "fig2_population_heatmap.png", bbox_inches="tight")
        f3.savefig(FIG_DIR / "fig3_raster_and_time_course.png", bbox_inches="tight")
        stats["csv_export"] = export_csv(data)
        with open(TABLE_DIR / "part_c_summary_stats.json", "w") as f:
            json.dump(stats, f, indent=2)
    return data, (f1, f2, f3), stats


if __name__ == "__main__":
    matplotlib.use("Agg")
    _, _, s = build_everything(save=True)
    print(json.dumps(s, indent=2))
    print("\nFigures saved to:", FIG_DIR)
    print("CSV files saved to:", CSV_DIR)
